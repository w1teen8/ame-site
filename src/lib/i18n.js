const ITEM_FORMS = {
  ua: { one: 'товар', few: 'товари', many: 'товарів', other: 'товару' },
  en: { one: 'item', other: 'items' },
}

export function itemsLabel(count, lang) {
  const rule = new Intl.PluralRules(lang === 'ua' ? 'uk' : 'en').select(count)
  const forms = ITEM_FORMS[lang]
  return `${count} ${forms[rule] ?? forms.other}`
}

export function formatPrice(value, lang) {
  return `${new Intl.NumberFormat(lang === 'ua' ? 'uk-UA' : 'en-US').format(value)} ₴`
}
